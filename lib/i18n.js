// Payment id (stored in DB) -> key in translations.*.payments
export const PAYMENT_ID_TO_KEY = {
  tarjeta_debito: 'debit',
  tarjeta_credito: 'credit',
  transferencia: 'transfer',
  efectivo: 'cash',
};

function normalizePaymentId(id) {
  return String(id ?? '')
    .trim()
    .toLowerCase()
    .replace(/[\s-]+/g, '_');
}

export function getCategoryLabel(categoryId, t) {
  if (!categoryId) return '';
  const key = CATEGORY_ID_TO_KEY[categoryId];
  if (key && t?.categories?.[key]) return t.categories[key];
  return String(categoryId);
}

export function getPaymentLabel(paymentId, t) {
  const key = PAYMENT_ID_TO_KEY[normalizePaymentId(paymentId)];
  if (key && t?.payments?.[key]) return t.payments[key];
  if (!paymentId) return '—';
  return String(paymentId).replace(/_/g, ' ');
}

export function numberLocale(locale) {
  return locale === 'en' ? 'en-US' : 'es-MX';
}

// Locale-aware "oct 2026" style month label for a YYYY-MM key.
export function formatMonthLabel(monthKey, locale = 'es') {
  if (!monthKey) return locale === 'en' ? 'Period' : 'Periodo';
  const [y, m] = String(monthKey).split('-').map(Number);
  if (!y || !m) return String(monthKey);
  const d = new Date(y, m - 1, 1);
  const tag = locale === 'en' ? 'en-US' : 'es-MX';
  return d.toLocaleDateString(tag, { month: 'short', year: 'numeric' }).replace('.', '');
}
